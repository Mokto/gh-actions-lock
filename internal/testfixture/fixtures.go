// Synthetic returns a 40-character SHA of c repeated, for commits that only
// exist in a fake API.
func Synthetic(c byte) string { return strings.Repeat(string(c), 40) }

// IsSynthetic reports whether sha is obviously fabricated ("aaaa…",
// "abc123abc123…"). Real object IDs use far more than seven distinct digits.
func IsSynthetic(sha string) bool {
	seen := map[rune]bool{}
	for _, r := range sha {
		seen[r] = true
	}
	return len(seen) < 8
}

// BySHA returns the pin whose SHA is sha.
func BySHA(sha string) (Pin, bool) {
	for _, p := range Pins() {
		if p.SHA == sha {
			return p, true
		}
	}
	return Pin{}, false
}

// Lockfile renders a v0.0.2 lockfile locking each workflow path to pins.
func Lockfile(workflows map[string][]Pin) string {
	paths := make([]string, 0, len(workflows))
	for p := range workflows {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b strings.Builder
	b.WriteString("# This file is machine-generated by `gh actions-lock`.\n" +
		"# Do not edit by hand; run `gh actions-lock` to update.\n" +
		"# Docs: https://gh.io/actions-lockfile\n" +
		"version: 'v0.0.2'\nworkflows:\n")
	deps := map[string]Pin{}
	for _, p := range paths {
		fmt.Fprintf(&b, "    '%s':\n", p)
		for _, pin := range workflows[p] {
			fmt.Fprintf(&b, "        - '%s'\n", pin.Uses())
			deps[pin.Uses()] = pin
		}
	}
	keys := make([]string, 0, len(deps))
	for k := range deps {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b.WriteString("dependencies:\n")
	for _, k := range keys {
		p := deps[k]
		fmt.Fprintf(&b, "    '%s':\n        ref: '%s'\n        commit: '%s'\n        owner_id: %d\n        repo_id: %d\n",
			k, p.Ref, p.Commit(), p.OwnerID, p.RepoID)
	}
	return b.String()
}

// LockfileTemplates are the named lockfiles catalog scenarios start from.
func LockfileTemplates() map[string]string {
	ci := ".github/workflows/ci.yml"
	// The all-zero commit is in no ref's history, so it reads as a forgery.
	forged := CheckoutV4
	forged.SHA = Synthetic('0')
	return map[string]string{
		"pinned_checkout":      Lockfile(map[string][]Pin{ci: {CheckoutV4}}),
		"pinned_checkout_full": Lockfile(map[string][]Pin{ci: {CheckoutV420}}),
		"pinned_checkout_main": Lockfile(map[string][]Pin{ci: {CheckoutMain}}),
		"pinned_checkout_plus_deleted": Lockfile(map[string][]Pin{
			ci:                              {CheckoutV4},
			".github/workflows/deleted.yml": {SetupGoV5},
		}),
		"forgery_stale_checkout": Lockfile(map[string][]Pin{ci: {forged}}),
		"future_version": "# This file is machine-generated by `gh actions-lock`.\n" +
			"version: 'v99.99.99'\nworkflows: {}\ndependencies: {}\n",
	}
}

